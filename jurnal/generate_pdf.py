def convert_md_to_pdf(md_filename, pdf_filename, is_journal=False):
    md_path = os.path.join(JURNAL_DIR, md_filename)
    html_path = os.path.join(JURNAL_DIR, md_filename.replace(".md", ".html"))
    pdf_path = os.path.join(JURNAL_DIR, pdf_filename)

    print(f"[*] Processing {md_filename} -> {pdf_filename}...")

    # Step 1: Pandoc MD to HTML
    cmd_pandoc = [
        "pandoc",
        md_path,
        "-s",
        "--mathjax",
        "--metadata", "title=",
        "-o", html_path
    ]
    res_pandoc = subprocess.run(cmd_pandoc, capture_output=True, text=True, cwd=JURNAL_DIR)
    if res_pandoc.returncode != 0:
        print(f"[!] Pandoc error on {md_filename}: {res_pandoc.stderr}")
        return False

    # Step 2: Inject Custom Academic CSS & Tag Abstracts/Captions
    with open(html_path, "r", encoding="utf-8") as f:
        html_content = f.read()

    # Clear title tag so Chrome never shows it in print headers
    html_content = re.sub(r'<title>.*?</title>', '<title></title>', html_content, flags=re.DOTALL)

    # 1. Tag caption paragraphs
    html_content = re.sub(
        r'<p>(<em>(?:Gambar|Figure|Tabel|Table)\s*\d+[^<]*</em>)</p>',
        r'<p class="caption">\1</p>',
        html_content
    )

    # 2. Tag abstract headings and their paragraphs
    pattern_abstrak = re.compile(
        r'(<h[23][^>]*id=["\'](?:abstrak|abstract)["\'][^>]*>.*?</h[23]>)\s*'
        r'((?:<p>.*?</p>\s*)+?)'
        r'(<p>(?:<strong>(?:Kata Kunci|Keywords):?</strong>|<em>(?:Kata Kunci|Keywords):?</em>).*?</p>)',
        re.DOTALL | re.IGNORECASE
    )

    def replace_abstrak(match):
        heading = match.group(1)
        p_body = match.group(2)
        p_keywords = match.group(3)
        p_body = re.sub(r'<p>', '<p class="abstract-text">', p_body, flags=re.IGNORECASE)
        p_keywords = re.sub(r'<p>', '<p class="keywords-text">', p_keywords, flags=re.IGNORECASE)
        return f'<div class="abstract-container">\n{heading}\n{p_body}\n{p_keywords}\n</div>'

    html_content = pattern_abstrak.sub(replace_abstrak, html_content)

    custom_style_block = f"<style>\n{ACADEMIC_CSS}\n</style>"
    if "</head>" in html_content:
        html_content = html_content.replace("</head>", f"{custom_style_block}\n</head>")
    else:
        html_content = f"{custom_style_block}\n{html_content}"

    with open(html_path, "w", encoding="utf-8") as f:
        f.write(html_content)

    # Step 3: Chrome Headless HTML to PDF
    import tempfile
    with tempfile.TemporaryDirectory() as temp_profile_dir:
        cmd_chrome = [
            "google-chrome",
            "--headless",
            "--disable-gpu",
            "--no-sandbox",
            "--disable-dev-shm-usage",
            "--no-pdf-header-footer",
            "--virtual-time-budget=2000",
            f"--user-data-dir={temp_profile_dir}",
            f"--print-to-pdf={pdf_path}",
            html_path
        ]
        try:
            res_chrome = subprocess.run(cmd_chrome, capture_output=True, text=True, cwd=JURNAL_DIR, timeout=20)
            if res_chrome.returncode != 0:
                print(f"[!] Chrome error on {md_filename}: {res_chrome.stderr}")
                return False
        except subprocess.TimeoutExpired:
            print(f"[!] Chrome rendering timed out on {md_filename}")
            return False

    # Step 4: Pandoc MD to DOCX
    docx_path = os.path.join(JURNAL_DIR, md_filename.replace(".md", ".docx"))
    cmd_docx = ["pandoc", md_path, "-o", docx_path]
    subprocess.run(cmd_docx, capture_output=True, text=True, cwd=JURNAL_DIR)

    if os.path.exists(pdf_path):
        size_mb = os.path.getsize(pdf_path) / (1024 * 1024)
        print(f"[✓] Successfully generated: {pdf_path} ({size_mb:.2f} MB)")
        if os.path.exists(docx_path):
            size_docx_mb = os.path.getsize(docx_path) / (1024 * 1024)
            print(f"[✓] Successfully generated: {docx_path} ({size_docx_mb:.2f} MB)")
        return True
    else:
        print(f"[!] PDF not found: {pdf_path}")
        return False

def main():
    # If a specific file is requested via CLI argument, only compile that file (lightning fast)
    if len(sys.argv) > 1:
        target = os.path.basename(sys.argv[1])
        pdf_name = target.replace(".md", ".pdf")
        is_journal = "JURNAL" in target.upper()
        if os.path.exists(os.path.join(JURNAL_DIR, target)):
            convert_md_to_pdf(target, pdf_name, is_journal)
            return
        else:
            print(f"[!] Target file not found: {target}")
            return

    files_to_convert = [
        ("DRAFT_JURNAL_ILMIAH_INDONESIA.md", "DRAFT_JURNAL_ILMIAH_INDONESIA.pdf", True),
        ("DRAFT_JURNAL_IJG_ENGLISH.md", "DRAFT_JURNAL_IJG_ENGLISH.pdf", True),
        ("DRAFT_TESIS_LENGKAP.md", "DRAFT_TESIS_LENGKAP.pdf", False),
    ]

    success_count = 0
    for md_file, pdf_file, is_journal in files_to_convert:
        if os.path.exists(os.path.join(JURNAL_DIR, md_file)):
            if convert_md_to_pdf(md_file, pdf_file, is_journal):
                success_count += 1
        else:
            print(f"[!] File not found: {md_file}")

    print(f"\n[DONE] {success_count}/{len(files_to_convert)} PDF files successfully compiled.")

if __name__ == "__main__":
    main()
